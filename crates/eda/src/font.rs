//! A small single-stroke font, the kind plotters and KiCad's own stroke font use, so
//! silkscreen text reaches Gerber and SVG outputs as real strokes. Glyphs are drawn on a
//! 4×6 grid (x right, y down); unknown characters plot as nothing.

/// Strokes of a glyph as polylines of grid points.
pub fn glyph(ch: char) -> &'static [&'static [(i8, i8)]] {
    match ch.to_ascii_uppercase() {
        '0' => &[&[(0, 0), (4, 0), (4, 6), (0, 6), (0, 0)], &[(0, 6), (4, 0)]],
        '1' => &[&[(1, 1), (2, 0), (2, 6)], &[(1, 6), (3, 6)]],
        '2' => &[&[(0, 0), (4, 0), (4, 3), (0, 3), (0, 6), (4, 6)]],
        '3' => &[&[(0, 0), (4, 0), (4, 6), (0, 6)], &[(1, 3), (4, 3)]],
        '4' => &[&[(0, 0), (0, 3), (4, 3)], &[(4, 0), (4, 6)]],
        '5' => &[&[(4, 0), (0, 0), (0, 3), (4, 3), (4, 6), (0, 6)]],
        '6' => &[&[(4, 0), (0, 0), (0, 6), (4, 6), (4, 3), (0, 3)]],
        '7' => &[&[(0, 0), (4, 0), (1, 6)]],
        '8' => &[&[(0, 0), (4, 0), (4, 6), (0, 6), (0, 0)], &[(0, 3), (4, 3)]],
        '9' => &[&[(4, 3), (0, 3), (0, 0), (4, 0), (4, 6), (0, 6)]],
        'A' => &[&[(0, 6), (0, 2), (2, 0), (4, 2), (4, 6)], &[(0, 3), (4, 3)]],
        'B' => &[
            &[(0, 0), (3, 0), (4, 1), (4, 2), (3, 3), (0, 3)],
            &[(3, 3), (4, 4), (4, 5), (3, 6), (0, 6), (0, 0)],
        ],
        'C' => &[&[(4, 0), (0, 0), (0, 6), (4, 6)]],
        'D' => &[&[(0, 0), (3, 0), (4, 1), (4, 5), (3, 6), (0, 6), (0, 0)]],
        'E' => &[&[(4, 0), (0, 0), (0, 6), (4, 6)], &[(0, 3), (3, 3)]],
        'F' => &[&[(4, 0), (0, 0), (0, 6)], &[(0, 3), (3, 3)]],
        'G' => &[&[(4, 0), (0, 0), (0, 6), (4, 6), (4, 3), (2, 3)]],
        'H' => &[&[(0, 0), (0, 6)], &[(4, 0), (4, 6)], &[(0, 3), (4, 3)]],
        'I' => &[&[(1, 0), (3, 0)], &[(2, 0), (2, 6)], &[(1, 6), (3, 6)]],
        'J' => &[&[(4, 0), (4, 6), (0, 6), (0, 4)]],
        'K' => &[&[(0, 0), (0, 6)], &[(4, 0), (0, 3), (4, 6)]],
        'L' => &[&[(0, 0), (0, 6), (4, 6)]],
        'M' => &[&[(0, 6), (0, 0), (2, 3), (4, 0), (4, 6)]],
        'N' => &[&[(0, 6), (0, 0), (4, 6), (4, 0)]],
        'O' => &[&[(0, 0), (4, 0), (4, 6), (0, 6), (0, 0)]],
        'P' => &[&[(0, 6), (0, 0), (4, 0), (4, 3), (0, 3)]],
        'Q' => &[&[(0, 0), (4, 0), (4, 6), (0, 6), (0, 0)], &[(2, 4), (4, 6)]],
        'R' => &[&[(0, 6), (0, 0), (4, 0), (4, 3), (0, 3), (4, 6)]],
        'S' => &[&[(4, 0), (0, 0), (0, 3), (4, 3), (4, 6), (0, 6)]],
        'T' => &[&[(0, 0), (4, 0)], &[(2, 0), (2, 6)]],
        'U' => &[&[(0, 0), (0, 6), (4, 6), (4, 0)]],
        'V' => &[&[(0, 0), (2, 6), (4, 0)]],
        'W' => &[&[(0, 0), (1, 6), (2, 3), (3, 6), (4, 0)]],
        'X' => &[&[(0, 0), (4, 6)], &[(4, 0), (0, 6)]],
        'Y' => &[&[(0, 0), (2, 3), (4, 0)], &[(2, 3), (2, 6)]],
        'Z' => &[&[(0, 0), (4, 0), (0, 6), (4, 6)]],
        '-' => &[&[(1, 3), (3, 3)]],
        '+' => &[&[(0, 3), (4, 3)], &[(2, 1), (2, 5)]],
        '.' => &[&[(2, 6), (2, 5)]],
        '_' => &[&[(0, 6), (4, 6)]],
        '/' => &[&[(0, 6), (4, 0)]],
        '(' => &[&[(3, 0), (2, 1), (2, 5), (3, 6)]],
        ')' => &[&[(1, 0), (2, 1), (2, 5), (1, 6)]],
        '#' => &[
            &[(1, 0), (1, 6)],
            &[(3, 0), (3, 6)],
            &[(0, 2), (4, 2)],
            &[(0, 4), (4, 4)],
        ],
        _ => &[],
    }
}

/// Polylines for `text` at `origin` (top-left), glyph height `h` in the caller's units;
/// `mirror` writes right to left mirrored, as bottom-side silkscreen reads.
pub fn strokes(text: &str, origin: (i64, i64), h: i64, mirror: bool) -> Vec<Vec<(i64, i64)>> {
    let unit = h / 6;
    let advance = unit * 6;
    let mut out = Vec::new();
    for (i, ch) in text.chars().enumerate() {
        let x0 = i as i64 * advance;
        for stroke in glyph(ch) {
            out.push(
                stroke
                    .iter()
                    .map(|(gx, gy)| {
                        let x = x0 + *gx as i64 * unit;
                        let y = *gy as i64 * unit;
                        (
                            if mirror { origin.0 - x } else { origin.0 + x },
                            origin.1 + y,
                        )
                    })
                    .collect(),
            );
        }
    }
    out
}
pub fn width(text: &str, h: i64) -> i64 {
    let n = text.chars().count() as i64;
    if n == 0 {
        0
    } else {
        (h / 6) * (6 * n - 2)
    }
}
