//! An independent determinism regression corpus: recorded goldens for long runs.
//!
//! A run of this engine is meant to be a pure function of (engine, world, seed,
//! action sequence, viewport). This file pins that claim down with data captured
//! from a known-good commit, so that any change to observable behaviour — a
//! different per-step hash, a renumbered event, a reordered event log, a snapshot
//! that exports different bytes, a `validate_snapshot` that stopped refusing
//! something — fails here with the step it happened at and both values.
//!
//! What is covered
//! ---------------
//! * Five scenarios over two worlds (`worlds/company-2026/world.json` and
//!   `worlds/agent-desktop/world.json`), five seeds and four machines — one of
//!   them a Windows box, so a second shell dialect is in the mix — 300 to 360
//!   steps each, 1 to 3 actions a step, over all seven built-in action families.
//! * `state_hash()` after **every** step, not only at the end, so a divergence is
//!   localised to the step that caused it.
//! * A digest of every `StepResult` — observation channels, per-action outcome,
//!   error code and refusal reason, tick and pending count.
//! * The complete event log: `sequence`, `tick`, `kind`, `machine`, `actor` in
//!   clear and a digest of `data`, plus a chained hash over the whole log so
//!   ordering and numbering cannot change unnoticed.
//! * A digest of `scene(1280, 800)` at every sampled step and of
//!   `scene(390, 844)` at the end, because `Environment::scene` is in the code
//!   being rewritten and the scene is observable output too.
//! * The action journal's head hash, which chains every recorded step.
//! * Snapshot / fork / restore: a mid-run snapshot, the exact byte length and
//!   SHA-256 of `export_snapshot()`, and two forks driven apart with different
//!   actions, each checked against its own golden.
//! * `Environment::replay` over the recorded journal, which must reproduce the
//!   same hashes (with step verification on, so the engine itself refuses a
//!   divergent replay).
//! * A snapshot exported at the baseline commit and committed as a fixture, which
//!   must still import and still hash the same.
//! * The negative half: `validate_snapshot` must still refuse a snapshot from a
//!   different world, an incompatible kernel version or engine string, mismatched
//!   application or interface module versions, a machine grant that is not in the
//!   world, a tampered journal, and a checkpoint with unresolved live host
//!   effects — each with the same error code *and* the same message.
//!
//! Diagnosing a divergence
//! -----------------------
//! If the step-result digests move but the state hashes do not, the difference is
//! inside `StepResult` rather than in world state. `dump_step_results` (ignored,
//! `CW_CORPUS_DUMP_DIR=<dir>`) writes every `StepResult` out in full; run it in a
//! worktree at the last good commit and in the tree under test and diff the two
//! directories, and the diff names the field.
//!
//! Regenerating the goldens
//! ------------------------
//! The goldens are not something you refresh to make a red test green. A change
//! here means the engine's observable output changed; that is either a bug or a
//! decision someone has to take deliberately. When it really is intended:
//!
//! ```text
//! CW_BLESS_DETERMINISM_CORPUS=yes-i-intend-to-change-observable-behaviour \
//!   cargo test -p computerworld --test determinism_corpus -- --ignored --exact \
//!   regenerate_determinism_goldens --nocapture
//! ```
//!
//! Both the `--ignored` filter and the exact pass-phrase are required; the test
//! refuses and prints why if either is missing. Commit the regenerated fixtures
//! in their own commit, with the reason for the behaviour change in the message,
//! so a reviewer sees the diff of what the engine now does.
//!
//! Note that `worlds/company-2026/world.json` is generated by
//! `scripts/build-content.sh`. If that file is regenerated the corpus will report
//! `the world definition itself changed` before any hash mismatch, so a content
//! change is never mistaken for an engine regression.

