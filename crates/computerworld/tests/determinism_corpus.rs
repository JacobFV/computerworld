fn digest(value: &impl Serialize) -> String {
    format!(
        "{:x}",
        Sha256::digest(serde_json::to_vec(value).expect("value serializes"))
    )
}

fn short(value: &impl Serialize) -> String {
    digest(value)[..16].to_string()
}

fn build(scenario: &Scenario) -> (World, String) {
    let definition =
        WorldDefinition::from_json(scenario.world.json()).expect("packaged world parses");
    let mut world = World::new(definition, scenario.seed).expect("world builds");
    let session = world
        .environment(EnvironmentConfig {
            actor: scenario.actor.into(),
            machines: scenario.machines.iter().map(|m| (*m).into()).collect(),
            actions: scenario.families.iter().map(|f| (*f).into()).collect(),
            observations: scenario.observations.iter().map(|o| (*o).into()).collect(),
            action_budget: 1024,
        })
        .expect("session grants are valid");
    world
        .interfaces_mut()
        .enable_replay_verification(scenario.verify_steps);
    (world, session)
}

/// Whether `state_hash()` is sampled at this step: on the stride, on the last
/// step, and at the checkpoint.
fn sampled(index: usize, len: usize, stride: usize) -> bool {
    index + 1 == len || (index + 1).is_multiple_of(stride)
}

/// The semantic scene the actor would see at the desktop viewport.
fn scene_digest(world: &World, session: &str) -> String {
    short(
        &world
            .scene(session, 1280, 800)
            .expect("the session may see the scene"),
    )
}

/// Drive `program`, sampling a state hash on the stride. `offset` is the step
/// number the first entry of `program` has in the scenario as a whole, so a
/// failure names the step a reader can find in the script.
fn drive(
    world: &mut World,
    session: &str,
    program: &[Vec<ActionEnvelope>],
    stride: usize,
    offset: usize,
) -> Vec<StepHash> {
    let mut hashes = Vec::new();
    for (index, actions) in program.iter().enumerate() {
        world
            .step(session, actions.clone())
            .expect("a granted step is dispatched, whatever its per-action outcomes");
        if sampled(index, program.len(), stride) {
            hashes.push(StepHash {
                step: offset + index,
                hash: world.state_hash().expect("state hashes"),
                scene: scene_digest(world, session),
            });
        }
    }
    hashes
}

/// The event log, as a chained hash plus one readable line per event.
fn event_log(world: &World) -> (usize, String, Vec<String>) {
    let events = world.trajectory();
    let mut chain = String::new();
    let mut records = Vec::with_capacity(events.len());
    for (index, event) in events.iter().enumerate() {
        chain = digest(&(index as u64, &chain, event));
        records.push(format!(
            "{}|{}|{}|{}|{}|{}",
            event.sequence,
            event.tick,
            event.kind,
            event.machine.as_deref().unwrap_or(""),
            event.actor.as_deref().unwrap_or(""),
            short(&event.data),
        ));
    }
    (events.len(), chain, records)
}

struct Observed {
    golden: Golden,
    /// The snapshot exported at `fork_at`, kept so the bless run can commit it.
    export: String,
}

/// `CW_CORPUS_TRACE=1` prints where the time goes, for anyone tuning the step
/// counts or chasing a slow phase.
fn trace(scenario: &Scenario, phase: &str, at: &std::time::Instant) {
    if std::env::var("CW_CORPUS_TRACE").is_ok() {
        println!("[{}] {phase}: {:?}", scenario.name, at.elapsed());
    }
}

fn observe(scenario: &Scenario) -> Observed {
    let clock = std::time::Instant::now();
    let program = main_script(scenario);
    let (mut world, session) = build(scenario);
    let initial = world.snapshot();

    let mut state_hashes: Vec<StepHash> = Vec::new();
    let mut result_digests = Vec::with_capacity(program.len());
    let mut checkpoint: Option<(String, String, usize)> = None;
    let mut forked: Option<World> = None;

    for (index, actions) in program.iter().enumerate() {
        let result = world
            .step(&session, actions.clone())
            .expect("a granted step is dispatched, whatever its per-action outcomes");
        result_digests.push(short(&result));
        if index % 20 == 19 {
            trace(scenario, &format!("step {}", index + 1), &clock);
        }
        let at_checkpoint = index + 1 == scenario.fork_at;
        if at_checkpoint || sampled(index, program.len(), scenario.hash_stride) {
            let hash = world.state_hash().expect("state hashes");
            if sampled(index, program.len(), scenario.hash_stride) {
                state_hashes.push(StepHash {
                    step: index,
                    hash: hash.clone(),
                    scene: scene_digest(&world, &session),
                });
            }
            if at_checkpoint {
                let snapshot = world.snapshot();
                let export = world.export_snapshot().expect("snapshot exports");
                forked = Some(world.fork(&snapshot).expect("a mid-run fork is allowed"));
                checkpoint = Some((hash, export.clone(), export.len()));
            }
        }
    }

    trace(scenario, "main run", &clock);
    let (event_count, event_chain, event_records) = event_log(&world);
    trace(scenario, "event log", &clock);

    let journal = world.interfaces().action_journal().clone();
    assert!(
        journal.verify().expect("journal is serializable"),
        "{}: the recorded action journal does not verify against its own hash chain",
        scenario.name
    );
    let journal_head = journal
        .entries
        .last()
        .map(|e| e.hash.clone())
        .unwrap_or_default();
    let journal_entries = journal.entries.len();

    // Replay: the same initial checkpoint plus the same journal must reproduce
    // the same state and the same event log, event for event. Where step
    // verification is on the engine refuses a divergent replay itself, with
    // `replay_diverged`; where it is off these two comparisons are the check.
    let mut replayed = World::new(
        WorldDefinition::from_json(scenario.world.json()).expect("packaged world parses"),
        scenario.seed,
    )
    .expect("world builds");
    replayed
        .interfaces_mut()
        .replay(&initial, &journal)
        .unwrap_or_else(|e| {
            panic!(
                "{}: replaying the recorded journal diverged: [{}] {}",
                scenario.name, e.code, e.message
            )
        });
    trace(scenario, "replay", &clock);
    let replayed_state_hash = replayed.state_hash().expect("state hashes");

    // And the same journal, stepped entry by entry into a second fresh world, must
    // produce the same `StepResult` for every step — the same observation, the same
    // outcome values and the same `ActionEffect`, digest field included.
    //
    // This is not a golden comparison; it is the contract `ActionEffect::state`
    // states for itself: "equal digests mean equal observable state, in this
    // process or after a snapshot restore". A reconstructed world computes every
    // digest from scratch, so a digest that is cached anywhere and not invalidated
    // when the thing it stands for changes reports the stale value in the live run
    // and the true one here, and this fails — which is the failure mode a golden
    // captured from the same build could never see.
    let mut reconstructed = World::new(
        WorldDefinition::from_json(scenario.world.json()).expect("packaged world parses"),
        scenario.seed,
    )
    .expect("world builds");
    reconstructed
        .restore(&initial)
        .expect("the initial checkpoint restores");
    for (index, entry) in journal.entries.iter().enumerate() {
        let result = reconstructed
            .step(&entry.value.session, entry.value.actions.clone())
            .expect("a recorded step dispatches again");
        let digest = short(&result);
        assert_eq!(
            digest, result_digests[index],
            "{}: step {index} produced a different StepResult when the journal was \
             stepped into a freshly restored world. The world state itself agrees, so \
             the difference is in what the step *reported*, not in what it did — the \
             likeliest cause is a value cached across steps that survived a change it \
             should have been invalidated by. Dump both streams with \
             CW_CORPUS_DUMP_DIR to see which field.",
            scenario.name
        );
    }
    let (_, replayed_event_chain, _) = event_log(&replayed);
    assert_eq!(
        replayed_state_hash,
        state_hashes.last().expect("the run has steps").hash,
        "{}: replay reproduced a different final state",
        scenario.name
    );
    assert_eq!(
        replayed_event_chain, event_chain,
        "{}: replay reproduced a different event log",
        scenario.name
    );

    // The two forks are driven apart and must stay independent.
    let (checkpoint_hash, export, export_bytes) = checkpoint.expect("fork_at is within the run");
    let mut fork = forked.expect("fork_at is within the run");
    fork.interfaces()
        .session(&session)
        .expect("the fork carries the session");
    let branch_a_program = steps_for(scenario, 1, scenario.branch_steps, scenario.steps);
    let branch_b_program = steps_for(scenario, 2, scenario.branch_steps, scenario.steps);
    let branch_a = drive(
        &mut world,
        &session,
        &branch_a_program,
        scenario.hash_stride,
        scenario.steps,
    );
    let branch_b = drive(
        &mut fork,
        &session,
        &branch_b_program,
        scenario.hash_stride,
        scenario.steps,
    );
    trace(scenario, "branches", &clock);
    let final_scene_390x844 = short(
        &world
            .scene(&session, 390, 844)
            .expect("the session may see the scene"),
    );
    assert_ne!(
        branch_a.last().map(|h| &h.hash),
        branch_b.last().map(|h| &h.hash),
        "{}: the two forks were driven with different actions and must not end in the same state",
        scenario.name
    );

    Observed {
        golden: Golden {
            corpus_version: CORPUS_VERSION,
            scenario: scenario.name.into(),
            world: scenario.world.name().into(),
            world_definition_sha256: format!("{:x}", Sha256::digest(scenario.world.json())),
            seed: scenario.seed,
            actor: scenario.actor.into(),
            machines: scenario.machines.iter().map(|m| (*m).into()).collect(),
            families: scenario.families.iter().map(|f| (*f).into()).collect(),
            steps: program.len(),
            actions: program.iter().map(Vec::len).sum(),
            script_sha256: digest(&program),
            state_hash_stride: scenario.hash_stride,
            step_state_hashes: state_hashes,
            step_result_digests: result_digests,
            journal_entries,
            journal_head,
            events: Events {
                count: event_count,
                chain_sha256: event_chain,
                records: event_records,
            },
            checkpoint: Checkpoint {
                at_step: scenario.fork_at,
                state_hash: checkpoint_hash,
                export_sha256: format!("{:x}", Sha256::digest(&export)),
                export_bytes,
                branch_a,
                branch_b,
                replayed_event_chain_sha256: replayed_event_chain,
                replayed_state_hash,
                final_scene_390x844,
            },
        },
        export,
    }
}

