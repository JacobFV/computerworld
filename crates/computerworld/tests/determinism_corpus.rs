#[test]
fn a_checkpoint_with_unresolved_live_host_effects_is_still_refused() {
    // A world whose gateway allows a host effect, so one can actually be started.
    let mut definition: Value =
        serde_json::from_str(AGENT_DESKTOP).expect("the example world parses");
    definition["network"]["gateway"] = json!({
        "allow_local": true,
        "allow_internet": false,
        "allow_host": true,
        "host_allowlist": ["example.com"],
        "sources": ["workstation"],
        "ports": [443],
        "schemes": ["https"],
        "allowed_cidrs": ["203.0.113.0/24"],
    });
    let json = serde_json::to_string(&definition).expect("the edited world serializes");
    let mut world = World::new(
        WorldDefinition::from_json(&json).expect("the edited world validates"),
        7,
    )
    .expect("world builds");

    let request = HttpRequest::json("GET", "https://example.com/", &json!({}))
        .expect("request is representable");
    world
        .runtime_mut()
        .begin_external("workstation", "ada", request, vec!["203.0.113.5".into()])
        .expect("the gateway policy above permits this host effect");

    // The source side refuses to produce a portable checkpoint at all.
    expect_refusal(
        "exporting a snapshot while a host effect is live",
        world.export_snapshot(),
        "external_effect_pending",
        "complete live host effects before portable snapshot or fork",
    );

    // And the restore side refuses one that claims a live effect.
    let snapshot = world.snapshot();
    let mut target = World::new(
        WorldDefinition::from_json(&json).expect("the edited world validates"),
        7,
    )
    .expect("world builds");
    expect_refusal(
        "restoring a checkpoint that carries an unresolved live host effect",
        target.restore(&snapshot),
        "external_effect_pending",
        "checkpoint contains live host effects",
    );
    expect_refusal(
        "forking a checkpoint that carries an unresolved live host effect",
        target.fork(&snapshot).map(|_| ()),
        "external_effect_pending",
        "checkpoint contains live host effects",
    );
    // The same refusal survives a round trip through JSON, which is how a
    // checkpoint reaches another process.
    let mut fresh = World::new(
        WorldDefinition::from_json(&json).expect("the edited world validates"),
        7,
    )
    .expect("world builds");
    let clean = fresh
        .export_snapshot()
        .expect("a world with no live effects exports");
    let mut value: Value = serde_json::from_str(&clean).expect("an exported snapshot is JSON");
    value["kernel"]["external_pending"] = json!(true);
    expect_refusal(
        "importing a checkpoint flagged with a live host effect",
        fresh.import_snapshot(&serde_json::to_string(&value).expect("serializes")),
        "external_effect_pending",
        "checkpoint contains live host effects",
    );
}

