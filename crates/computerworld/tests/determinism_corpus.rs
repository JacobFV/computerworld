/// Export, edit one field of the JSON, and try to import it again.
fn tampered(world: &World, edit: impl FnOnce(&mut Value)) -> String {
    let mut value: Value = serde_json::from_str(
        &world
            .export_snapshot()
            .expect("a world with no live effects exports"),
    )
    .expect("an exported snapshot is JSON");
    edit(&mut value);
    serde_json::to_string(&value).expect("the edited snapshot serializes")
}

