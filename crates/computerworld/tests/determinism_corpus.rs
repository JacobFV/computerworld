/// splitmix64. The scripts must be a pure function of the scenario and nothing
/// the engine says, or a behaviour change would silently change the program the
/// corpus is measuring.
struct Rng(u64);
impl Rng {
    fn new(seed: u64) -> Self {
        Self(seed)
    }
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^ (z >> 31)
    }
    fn below(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }
    fn pick<'a, T>(&mut self, items: &'a [T]) -> &'a T {
        &items[self.below(items.len())]
    }
}

fn name_seed(name: &str) -> u64 {
    let mut h = 0xcbf2_9ce4_8422_2325u64;
    for b in name.as_bytes() {
        h ^= u64::from(*b);
        h = h.wrapping_mul(0x1000_0000_01b3);
    }
    h
}

/// The simulated Windows shell speaks a different dialect; terminal work in the
/// scripts stays on the POSIX machines and the Windows box is driven through the
/// other families.
fn posix(machine: &str) -> bool {
    !machine.contains("windows")
}

const SCRATCH: &str = "/tmp/cw-corpus";

fn terminal_action(rng: &mut Rng, machine: &str, i: usize) -> ActionEnvelope {
    let command = match rng.below(16) {
        0 => format!("echo \"line {i}\" >> {SCRATCH}/log.txt"),
        1 => format!("mkdir -p {SCRATCH}/d{}", i % 7),
        2 => format!("ls -la {SCRATCH}"),
        3 => format!("cat {SCRATCH}/log.txt"),
        4 => format!("wc -l {SCRATCH}/log.txt"),
        5 => "pwd".to_string(),
        6 => "whoami".to_string(),
        7 => format!("printf 'a%sb\\n' {i}"),
        8 => format!("sha256sum {SCRATCH}/log.txt"),
        9 => format!("sort {SCRATCH}/log.txt | head -3"),
        10 => format!("touch {SCRATCH}/t{}.txt", i % 5),
        11 => format!("sed -n '1,2p' {SCRATCH}/log.txt"),
        12 => format!("rm -f {SCRATCH}/t{}.txt", i % 5),
        13 => format!("seq 1 {}", i % 9 + 1),
        14 => format!("stat {SCRATCH}/log.txt"),
        _ => format!("grep -c line {SCRATCH}/log.txt"),
    };
    ActionEnvelope::new(
        "terminal.v1",
        "execute",
        machine,
        json!({"command": command}),
    )
}

fn filesystem_action(rng: &mut Rng, machine: &str, i: usize) -> ActionEnvelope {
    let path = format!("{SCRATCH}/f{}.txt", i % 11);
    match rng.below(4) {
        0 => ActionEnvelope::new(
            "filesystem.v1",
            "write",
            machine,
            json!({"path": path, "content": format!("payload {i}\n")}),
        ),
        1 => ActionEnvelope::new("filesystem.v1", "read", machine, json!({"path": path})),
        2 => ActionEnvelope::new("filesystem.v1", "list", machine, json!({"path": SCRATCH})),
        _ => ActionEnvelope::new("filesystem.v1", "stat", machine, json!({"path": path})),
    }
}

