fn expect_refusal<T>(what: &str, got: Result<T, SimError>, code: &str, message: &str) {
    match got {
        Ok(_) => panic!(
            "{what}: accepted. `validate_snapshot` must still refuse this with [{code}] {message}.\n\
             Silently accepting an invalid checkpoint is the most dangerous outcome a performance\n\
             change can have here: nothing else in the suite would catch it."
        ),
        Err(e) => assert_eq!(
            (e.code.as_str(), e.message.as_str()),
            (code, message),
            "{what}: refused, but with a different error identity"
        ),
    }
}

