#[test]
#[ignore = "regenerating the determinism goldens is a deliberate act; see the module docs"]
fn regenerate_determinism_goldens() {
    let phrase = std::env::var(BLESS_VAR).unwrap_or_default();
    assert_eq!(
        phrase, BLESS_PHRASE,
        "\n\nRefusing to regenerate the determinism goldens.\n\
         These fixtures record what the engine observably does. Overwriting them hides a\n\
         behaviour change rather than explaining it. If the change is intended, say so:\n\n  \
         {BLESS_VAR}={BLESS_PHRASE} \\\n    cargo test -p computerworld --test determinism_corpus \
         -- --ignored --exact regenerate_determinism_goldens --nocapture\n\n\
         and commit the result on its own, with the reason in the commit message.\n"
    );
    std::fs::create_dir_all(golden_dir()).expect("the golden directory is writable");
    for (index, scenario) in SCENARIOS.iter().enumerate() {
        let observed = observe(scenario);
        let path = golden_path(scenario.name);
        std::fs::write(
            &path,
            serde_json::to_string_pretty(&observed.golden).expect("the golden serializes") + "\n",
        )
        .expect("the golden is writable");
        println!(
            "wrote {} ({} steps, {} events, {} bytes)",
            path.display(),
            observed.golden.steps,
            observed.golden.events.count,
            std::fs::metadata(&path).map(|m| m.len()).unwrap_or(0),
        );
        if index == PORTABLE_SNAPSHOT_SCENARIO {
            std::fs::write(snapshot_fixture_path(), &observed.export)
                .expect("the snapshot fixture is writable");
            println!(
                "wrote {} ({} bytes)",
                snapshot_fixture_path().display(),
                observed.export.len()
            );
        }
    }
}
