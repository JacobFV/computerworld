fn load(name: &str) -> Golden {
    let path = golden_path(name);
    let text = std::fs::read_to_string(&path).unwrap_or_else(|_| panic!("{}", missing(&path)));
    serde_json::from_str(&text)
        .unwrap_or_else(|e| panic!("golden {} is not readable: {e}", path.display()))
}

// ---------------------------------------------------------------------------
// Comparison, with a failure message worth reading
// ---------------------------------------------------------------------------

struct Report {
    scenario: String,
    problems: Vec<String>,
}
impl Report {
    fn new(scenario: &str) -> Self {
        Self {
            scenario: scenario.into(),
            problems: Vec::new(),
        }
    }
    fn field(
        &mut self,
        what: &str,
        observed: impl std::fmt::Display,
        golden: impl std::fmt::Display,
    ) {
        let (observed, golden) = (observed.to_string(), golden.to_string());
        if observed != golden {
            self.problems
                .push(format!("{what}: {observed} — expected {golden}"));
        }
    }
    /// Sampled state hashes, reported by the step they were taken at.
    fn hashes(&mut self, what: &str, observed: &[StepHash], golden: &[StepHash]) {
        if observed.len() != golden.len() {
            self.problems.push(format!(
                "{what}: {} samples — expected {}",
                observed.len(),
                golden.len()
            ));
        }
        let mut shown = 0;
        let mut total = 0;
        for (o, g) in observed.iter().zip(golden) {
            if o != g {
                total += 1;
                if shown < 5 {
                    shown += 1;
                    self.problems.push(if o.step != g.step {
                        format!(
                            "{what}: sample at step {} — expected a sample at step {}",
                            o.step, g.step
                        )
                    } else if o.hash != g.hash {
                        format!(
                            "{what} {}: state hash {} — expected {}",
                            o.step, o.hash, g.hash
                        )
                    } else {
                        format!(
                            "{what} {}: scene(1280x800) digest {} — expected {}",
                            o.step, o.scene, g.scene
                        )
                    });
                }
            }
        }
        if total > shown {
            self.problems
                .push(format!("{what}: and {} more differences", total - shown));
        }
    }
    /// Per-element comparison that names the index and stops after a few, so the
    /// message points at the first divergence rather than dumping the run.
    fn series(&mut self, what: &str, observed: &[String], golden: &[String]) {
        if observed.len() != golden.len() {
            self.problems.push(format!(
                "{what}: {} entries — expected {}",
                observed.len(),
                golden.len()
            ));
        }
        let mut shown = 0;
        let mut total = 0;
        for index in 0..observed.len().min(golden.len()) {
            if observed[index] != golden[index] {
                total += 1;
                if shown < 5 {
                    shown += 1;
                    self.problems.push(format!(
                        "{what} {index}: {} — expected {}",
                        observed[index], golden[index]
                    ));
                }
            }
        }
        if total > shown {
            self.problems
                .push(format!("{what}: and {} more differences", total - shown));
        }
    }
    fn finish(self) {
        if self.problems.is_empty() {
            return;
        }
        panic!(
            "determinism corpus `{}` diverged from its golden:\n  {}\n\n\
             This engine's contract is that a run is a pure function of (engine, world, seed,\n\
             action sequence, viewport). A difference above means observable behaviour changed.\n\
             Diagnose it before touching this fixture. If the change really is intended, see the\n\
             regeneration instructions at the top of tests/determinism_corpus.rs — it takes the\n\
             {BLESS_VAR} pass-phrase and belongs in its own commit.",
            self.scenario,
            self.problems.join("\n  ")
        );
    }
}

fn check(scenario: &Scenario) {
    let golden = load(scenario.name);
    // Checked first and on their own: if the fixture or the world file moved, say so
    // before running 300 steps and blaming the engine for it.
    let mut preflight = Report::new(scenario.name);
    preflight.field("corpus version", CORPUS_VERSION, golden.corpus_version);
    preflight.field(
        "the world definition file itself changed (a content change, not an engine regression) sha256",
        format!("{:x}", Sha256::digest(scenario.world.json())),
        &golden.world_definition_sha256,
    );
    preflight.finish();

    let mut report = Report::new(scenario.name);
    let observed = observe(scenario).golden;
    report.field("steps", observed.steps, golden.steps);
    report.field("actions", observed.actions, golden.actions);
    report.field(
        "action script sha256 (the generator in this file was edited)",
        &observed.script_sha256,
        &golden.script_sha256,
    );
    report.field(
        "state hash stride",
        observed.state_hash_stride,
        golden.state_hash_stride,
    );
    report.hashes(
        "step",
        &observed.step_state_hashes,
        &golden.step_state_hashes,
    );
    report.series(
        "step result digest at step",
        &observed.step_result_digests,
        &golden.step_result_digests,
    );
    report.field(
        "journal entries",
        observed.journal_entries,
        golden.journal_entries,
    );
    report.field(
        "journal head hash",
        &observed.journal_head,
        &golden.journal_head,
    );
    report.field("event count", observed.events.count, golden.events.count);
    report.field(
        "event log chain hash",
        &observed.events.chain_sha256,
        &golden.events.chain_sha256,
    );
    report.series("event", &observed.events.records, &golden.events.records);
    report.field(
        "checkpoint state hash",
        &observed.checkpoint.state_hash,
        &golden.checkpoint.state_hash,
    );
    report.field(
        "exported snapshot bytes",
        observed.checkpoint.export_bytes,
        golden.checkpoint.export_bytes,
    );
    report.field(
        "exported snapshot sha256",
        &observed.checkpoint.export_sha256,
        &golden.checkpoint.export_sha256,
    );
    report.hashes(
        "fork branch A, step",
        &observed.checkpoint.branch_a,
        &golden.checkpoint.branch_a,
    );
    report.hashes(
        "fork branch B, step",
        &observed.checkpoint.branch_b,
        &golden.checkpoint.branch_b,
    );
    report.field(
        "state hash after replaying the journal",
        &observed.checkpoint.replayed_state_hash,
        &golden.checkpoint.replayed_state_hash,
    );
    report.field(
        "event log chain hash after replaying the journal",
        &observed.checkpoint.replayed_event_chain_sha256,
        &golden.checkpoint.replayed_event_chain_sha256,
    );
    report.field(
        "scene(390x844) digest at the end of branch A",
        &observed.checkpoint.final_scene_390x844,
        &golden.checkpoint.final_scene_390x844,
    );
    report.finish();
}

