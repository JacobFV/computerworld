struct Scenario {
    name: &'static str,
    world: WorldKind,
    seed: u64,
    actor: &'static str,
    machines: &'static [&'static str],
    families: &'static [&'static str],
    observations: &'static [&'static str],
    /// Steps in the main run, before the mid-run checkpoint is taken.
    steps: usize,
    /// Step index the checkpoint is taken at; the two forks start here.
    fork_at: usize,
    /// Steps driven down each fork, with different actions on each side.
    branch_steps: usize,
    /// `state_hash()` is recorded every `hash_stride` steps (and always on the
    /// last step and at the checkpoint). It is 1 — every step — wherever that is
    /// affordable. On `company-2026` one `state_hash()` canonicalises a 3.7 MB
    /// world definition and costs ~0.7 s in a debug build, so per-step hashing
    /// there would make this suite take three quarters of an hour. Divergence is
    /// still localised to the exact step by the per-step `StepResult` digests and
    /// by the event log, which are recorded for every step of every scenario; the
    /// strided state hash is the backstop for state those two do not expose.
    hash_stride: usize,
    /// Ask the engine to hash after every step and refuse a divergent replay
    /// itself. Same cost consideration as `hash_stride`.
    verify_steps: bool,
}

