fn http_action(rng: &mut Rng, machine: &str, urls: &[&str]) -> ActionEnvelope {
    let url = *rng.pick(urls);
    let request = HttpRequest::json("GET", url, &json!({})).expect("request is representable");
    ActionEnvelope::new(
        "http.v1",
        "request",
        machine,
        serde_json::to_value(request).expect("request serializes"),
    )
}

fn one_action(rng: &mut Rng, scenario: &Scenario, i: usize) -> ActionEnvelope {
    let machine = *rng.pick(scenario.machines);
    let mut family = *rng.pick(scenario.families);
    if family == "terminal.v1" && !posix(machine) {
        family = "filesystem.v1";
    }
    match family {
        "terminal.v1" => terminal_action(rng, machine, i),
        "filesystem.v1" => filesystem_action(rng, machine, i),
        "application.v1" => application_action(rng, machine, i),
        "browser.v1" => browser_action(rng, machine, scenario.world.urls(), i),
        "keyboard.v1" => keyboard_action(rng, machine, i),
        "pointer.v1" => pointer_action(rng, machine),
        "http.v1" => http_action(rng, machine, scenario.world.urls()),
        other => unreachable!("unhandled family {other}"),
    }
}

/// The whole program for a scenario: the main run, then branch A, then branch B.
/// `salt` separates the two branches so the forks are driven apart.
fn steps_for(
    scenario: &Scenario,
    salt: u64,
    count: usize,
    start: usize,
) -> Vec<Vec<ActionEnvelope>> {
    let mut rng = Rng::new(
        name_seed(scenario.name) ^ scenario.seed.rotate_left(17) ^ salt.wrapping_mul(0x2545_f491),
    );
    // A scratch directory to accumulate state in, on every POSIX machine.
    let mut program: Vec<Vec<ActionEnvelope>> = Vec::with_capacity(count + 1);
    if salt == 0 {
        let prologue: Vec<ActionEnvelope> = scenario
            .machines
            .iter()
            .filter(|m| posix(m) && scenario.families.contains(&"terminal.v1"))
            .map(|m| {
                ActionEnvelope::new(
                    "terminal.v1",
                    "execute",
                    *m,
                    json!({"command": format!("mkdir -p {SCRATCH}")}),
                )
            })
            .collect();
        if !prologue.is_empty() {
            program.push(prologue);
        }
    }
    while program.len() < count {
        let i = start + program.len();
        let batch = 1 + rng.below(3);
        program.push(
            (0..batch)
                .map(|_| one_action(&mut rng, scenario, i))
                .collect(),
        );
    }
    program
}

fn main_script(scenario: &Scenario) -> Vec<Vec<ActionEnvelope>> {
    steps_for(scenario, 0, scenario.steps, 0)
}

