/// When the step-result digests diverge but the state hashes do not, the
/// difference is somewhere inside `StepResult` — an observation channel, an
/// outcome value, a refusal reason or an `ActionEffect`. This writes every
/// `StepResult` of every scenario out in full, so the same command run in a tree
/// at the last good commit and in the tree under test gives two files to diff,
/// and the diff names the field.
///
/// ```text
/// CW_CORPUS_DUMP_DIR=/tmp/before cargo test -p computerworld \
///   --test determinism_corpus -- --ignored --exact dump_step_results
/// ```
#[test]
#[ignore = "a diagnostic, not a check; set CW_CORPUS_DUMP_DIR"]
fn dump_step_results() {
    let dir = std::env::var("CW_CORPUS_DUMP_DIR")
        .expect("set CW_CORPUS_DUMP_DIR to the directory to write the dumps into");
    std::fs::create_dir_all(&dir).expect("the dump directory is writable");
    for scenario in SCENARIOS {
        let program = main_script(scenario);
        let (mut world, session) = build(scenario);
        let results: Vec<_> = program
            .iter()
            .map(|actions| {
                world
                    .step(&session, actions.clone())
                    .expect("a granted step is dispatched")
            })
            .collect();
        let path = PathBuf::from(&dir).join(format!("{}.json", scenario.name));
        std::fs::write(
            &path,
            serde_json::to_string_pretty(&results).expect("step results serialize"),
        )
        .expect("the dump is writable");
        println!("wrote {}", path.display());
    }
}

