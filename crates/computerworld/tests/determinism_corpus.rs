#[derive(Serialize, Deserialize)]
struct Golden {
    corpus_version: u32,
    scenario: String,
    world: String,
    /// SHA-256 of the world definition file, so a regenerated world is reported
    /// as such instead of looking like an engine regression.
    world_definition_sha256: String,
    seed: u64,
    actor: String,
    machines: Vec<String>,
    families: Vec<String>,
    steps: usize,
    actions: usize,
    /// SHA-256 of the generated action script. If this moves, the generator was
    /// edited and every hash below is measuring a different program.
    script_sha256: String,
    /// How often `state_hash()` was sampled; see `Scenario::hash_stride`.
    state_hash_stride: usize,
    /// `state_hash()` at each sampled step of the main run.
    step_state_hashes: Vec<StepHash>,
    /// Digest of the whole `StepResult` after each step of the main run.
    step_result_digests: Vec<String>,
    journal_entries: usize,
    journal_head: String,
    events: Events,
    checkpoint: Checkpoint,
}

#[derive(Serialize, Deserialize)]
struct Events {
    count: usize,
    /// Rolling hash over every event in order: `h(i, h(i-1), event)`.
    chain_sha256: String,
    /// `sequence|tick|kind|machine|actor|sha256(data)[..16]`, one per event.
    records: Vec<String>,
}

/// One sample, carrying the step it was taken at so a failure can say "step 417"
/// rather than "element 20". `scene` is a digest of `scene(1280, 800)`, which is
/// built by `Environment::scene` — one of the files being rewritten — and is
/// observable behaviour in its own right.
#[derive(Serialize, Deserialize, PartialEq)]
struct StepHash {
    step: usize,
    hash: String,
    scene: String,
}

#[derive(Serialize, Deserialize)]
struct Checkpoint {
    at_step: usize,
    state_hash: String,
    export_sha256: String,
    export_bytes: usize,
    /// The original world, driven on after the checkpoint.
    branch_a: Vec<StepHash>,
    /// A fork of the checkpoint, driven with different actions.
    branch_b: Vec<StepHash>,
    /// Digest of every event the replayed world produced, which must equal the
    /// main run's `events.chain_sha256`.
    replayed_event_chain_sha256: String,
    replayed_state_hash: String,
    /// A second viewport at the end of branch A, so a scene change that only
    /// shows at another size is caught too.
    final_scene_390x844: String,
}

